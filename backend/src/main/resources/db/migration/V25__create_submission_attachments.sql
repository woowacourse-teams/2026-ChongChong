CREATE TABLE submission_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL REFERENCES assignment_submissions (id) ON DELETE CASCADE,
    file_id BIGINT NOT NULL REFERENCES file_metadata (id),
    sort_order INTEGER NOT NULL CHECK (sort_order >= 0),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_submission_attachment_file UNIQUE (file_id),
    CONSTRAINT uk_submission_attachment_order UNIQUE (submission_id, sort_order)
);
