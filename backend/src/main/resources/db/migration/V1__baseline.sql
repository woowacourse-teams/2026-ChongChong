-- Baseline schema captured before Flyway adoption, formatted for readability.

CREATE TABLE users
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at        TIMESTAMP(6) WITHOUT TIME ZONE,
    name              VARCHAR(255) NOT NULL,
    profile_image_url VARCHAR(2048)
);

CREATE TABLE studies
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at  TIMESTAMP(6) WITHOUT TIME ZONE,
    description VARCHAR(255),
    name        VARCHAR(255) NOT NULL
);

CREATE TABLE study_members
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at        TIMESTAMP(6) WITHOUT TIME ZONE,
    name              VARCHAR(255) NOT NULL,
    profile_image_url VARCHAR(2048),
    role              VARCHAR(255) NOT NULL,
    study_id          BIGINT       NOT NULL,
    user_id           BIGINT       NOT NULL,
    CONSTRAINT study_members_role_check CHECK (role IN ('LEADER', 'MEMBER')),
    CONSTRAINT uk_study_members_study_user UNIQUE (study_id, user_id),
    CONSTRAINT fkb8cp6e23p040p7ml6sswen5cs FOREIGN KEY (study_id) REFERENCES studies (id),
    CONSTRAINT fkdt5hp8mbe53a5sdcecsf7wpyg FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE assignments
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at        TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at        TIMESTAMP(6) WITHOUT TIME ZONE,
    close_at          TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    content           TEXT                           NOT NULL,
    submission_method VARCHAR(255),
    title             VARCHAR(255)                   NOT NULL,
    study_id          BIGINT                         NOT NULL,
    CONSTRAINT fkqe029wvx6pjp0q8tlypilk0c9 FOREIGN KEY (study_id) REFERENCES studies (id)
);

CREATE TABLE assignment_reminders
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    remind_at     TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    status        VARCHAR(255)                   NOT NULL,
    assignment_id BIGINT                         NOT NULL,
    CONSTRAINT assignment_reminders_status_check CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT fk23if7m1gm235fcgs3hleq5do2 FOREIGN KEY (assignment_id) REFERENCES assignments (id)
);

CREATE TABLE assignment_submissions
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at    TIMESTAMP(6) WITHOUT TIME ZONE,
    content       TEXT,
    link          TEXT,
    submitted     BOOLEAN NOT NULL,
    submitted_at  TIMESTAMP(6) WITHOUT TIME ZONE,
    assignment_id BIGINT  NOT NULL,
    member_id     BIGINT  NOT NULL,
    CONSTRAINT uk_assignment_submissions_assignment_member UNIQUE (assignment_id, member_id),
    CONSTRAINT fkm7i7ubgh7y2n6mvg8muw62oax FOREIGN KEY (assignment_id) REFERENCES assignments (id),
    CONSTRAINT fknsfnkdmpdvd605vnpkpt1g0md FOREIGN KEY (member_id) REFERENCES study_members (id)
);

CREATE TABLE notices
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE,
    content    TEXT         NOT NULL,
    title      VARCHAR(255) NOT NULL,
    study_id   BIGINT       NOT NULL,
