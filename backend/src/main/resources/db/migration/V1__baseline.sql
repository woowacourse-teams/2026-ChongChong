    CONSTRAINT fko5m57o40ivnn0td7m511dx42k FOREIGN KEY (study_id) REFERENCES studies (id)
);

CREATE TABLE auth_sessions
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at         TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at         TIMESTAMP(6) WITHOUT TIME ZONE,
    expires_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    refresh_token_hash VARCHAR(64)                 NOT NULL,
    user_id            BIGINT                      NOT NULL,
    CONSTRAINT uk_auth_sessions_refresh_token_hash UNIQUE (refresh_token_hash),
    CONSTRAINT uk_auth_sessions_user_id UNIQUE (user_id),
    CONSTRAINT fkpu507182mdfutajr71rgk67l FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE push_tokens
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMP(6) WITHOUT TIME ZONE,
    updated_at      TIMESTAMP(6) WITHOUT TIME ZONE,
    installation_id VARCHAR(255) NOT NULL,
    is_active       BOOLEAN      NOT NULL,
