CREATE TABLE notice_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id BIGINT NOT NULL REFERENCES notices (id) ON DELETE CASCADE,
    file_id BIGINT NOT NULL REFERENCES file_metadata (id),
    sort_order INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_notice_attachment_file UNIQUE (file_id),
    CONSTRAINT uk_notice_attachment_order UNIQUE (notice_id, sort_order),
    CONSTRAINT ck_notice_attachment_sort_order CHECK (sort_order >= 0)
);
