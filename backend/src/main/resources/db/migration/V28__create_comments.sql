CREATE TABLE comments
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_type    VARCHAR(255) NOT NULL,
    resource_id      BIGINT NOT NULL,
    author_user_id   BIGINT,
    author_member_id BIGINT,
    content          TEXT NOT NULL,
    created_at       TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at       TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    edited_at        TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT ck_comments_resource_type
        CHECK (resource_type IN ('NOTICE', 'ASSIGNMENT', 'ASSIGNMENT_SUBMISSION')),
    CONSTRAINT ck_comments_resource_id CHECK (resource_id > 0),
    CONSTRAINT ck_comments_content_length CHECK (CHAR_LENGTH(content) BETWEEN 1 AND 1000),
    CONSTRAINT fk_comments_author_user
        FOREIGN KEY (author_user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_comments_author_member
        FOREIGN KEY (author_member_id) REFERENCES study_members (id) ON DELETE SET NULL
);

CREATE INDEX idx_comments_resource_order ON comments (resource_type, resource_id, id);
CREATE INDEX idx_comments_author_user ON comments (author_user_id);
CREATE INDEX idx_comments_author_member ON comments (author_member_id);

