-- Recurring assignment rules generate one assignment per occurrence (ADR-0064).
CREATE TABLE assignment_recurrences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_id BIGINT NOT NULL REFERENCES studies (id) ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    submission_method TEXT,
    submission_visibility VARCHAR(255) NOT NULL,
    submitter_mode VARCHAR(255) NOT NULL,
    submission_target VARCHAR(255),
    close_time TIME NOT NULL,
    interval_weeks INTEGER NOT NULL,
    next_occurrence_date DATE NOT NULL,
    next_publish_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT ck_assignment_recurrences_submission_visibility
        CHECK (submission_visibility IN ('LEADER_ONLY', 'ALL_STUDY_MEMBERS')),
    CONSTRAINT ck_assignment_recurrences_submitter_mode
        CHECK (submitter_mode IN ('RANGE', 'SELECTED')),
    CONSTRAINT ck_assignment_recurrences_submission_target
        CHECK (submission_target IN ('MEMBERS_ONLY', 'MEMBERS_AND_LEADER')),
    -- RANGE rules resolve submitters from the target; SELECTED rules use assignment_recurrence_submitters.
    CONSTRAINT ck_assignment_recurrences_target_by_mode
        CHECK ((submitter_mode = 'RANGE') = (submission_target IS NOT NULL)),
    CONSTRAINT ck_assignment_recurrences_interval_weeks
        CHECK (interval_weeks BETWEEN 1 AND 4)
);

CREATE INDEX idx_assignment_recurrences_study_id ON assignment_recurrences (study_id);
CREATE INDEX idx_assignment_recurrences_next_publish_at ON assignment_recurrences (next_publish_at);

CREATE TABLE assignment_recurrence_reminders (
    recurrence_id BIGINT NOT NULL REFERENCES assignment_recurrences (id) ON DELETE CASCADE,
    minutes_before_close INTEGER NOT NULL,
    PRIMARY KEY (recurrence_id, minutes_before_close),
    CONSTRAINT ck_assignment_recurrence_reminders_minutes CHECK (minutes_before_close > 0)
);

-- Members who leave the study drop out of SELECTED rules through the cascade.
CREATE TABLE assignment_recurrence_submitters (
    recurrence_id BIGINT NOT NULL REFERENCES assignment_recurrences (id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES study_members (id) ON DELETE CASCADE,
    PRIMARY KEY (recurrence_id, member_id)
);

CREATE INDEX idx_assignment_recurrence_submitters_member_id ON assignment_recurrence_submitters (member_id);

-- Generated occurrences outlive their rule, so the link is cleared instead of cascading.
ALTER TABLE assignments
    ADD COLUMN recurrence_id BIGINT REFERENCES assignment_recurrences (id) ON DELETE SET NULL;

ALTER TABLE assignments
    ADD COLUMN occurrence_date DATE;

-- occurrence_date stays after the rule is deleted, so only the forward direction is required.
ALTER TABLE assignments
    ADD CONSTRAINT ck_assignments_recurrence_occurrence_date
        CHECK (recurrence_id IS NULL OR occurrence_date IS NOT NULL);

ALTER TABLE assignments
    ADD CONSTRAINT uk_assignments_recurrence_occurrence UNIQUE (recurrence_id, occurrence_date);
